/**
 * Build-time pipeline for the atmosphere images (content/atmosphere/*.jpg).
 * These are art-direction visuals, never works: they become the persistent
 * particle system's targets and the no-WebGL page's section visuals.
 *
 * For each image: AVIF + WebP at 1600 and 800 px wide (lazy section
 * visuals), and a 256 × 256 lossless WebP "target" (colour; depth is taken
 * from luminance in the shader) the particles sample. Writes
 * src/content/atmosphere.generated.ts.
 */
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "content", "atmosphere");
const outDir = join(root, "public", "atmosphere");
mkdirSync(srcDir, { recursive: true });
mkdirSync(outDir, { recursive: true });
const fresh = (src, out) => existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs;

const items = [];
for (const f of readdirSync(srcDir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort()) {
  const id = f.replace(/\.(jpe?g|png|webp)$/i, "");
  const src = join(srcDir, f);
  const meta = await sharp(src).metadata();
  const out = {};
  for (const w of [1600, 800]) {
    for (const [ext, fn] of [["avif", (s) => s.avif({ quality: 52, effort: 4 })], ["webp", (s) => s.webp({ quality: 80, effort: 5 })]]) {
      const o = join(outDir, `${id}-${w}.${ext}`);
      if (!fresh(src, o)) await fn(sharp(src).resize({ width: Math.min(w, meta.width), withoutEnlargement: true })).toFile(o);
      out[`${ext}${w}`] = `/atmosphere/${id}-${w}.${ext}`;
    }
  }
  const t = join(outDir, `${id}-target.webp`);
  if (!fresh(src, t)) await sharp(src).resize(256, 256, { fit: "fill" }).webp({ lossless: true }).toFile(t);
  items.push({ id, w: meta.width, h: meta.height, aspect: +(meta.width / meta.height).toFixed(4), ...out, target: `/atmosphere/${id}-target.webp` });
}
const ts = `/* generated by scripts/prepare-atmosphere.mjs — do not edit */
export interface Atmo { id: string; w: number; h: number; aspect: number; avif1600: string; webp1600: string; avif800: string; webp800: string; target: string }
export const atmosphere: Atmo[] = ${JSON.stringify(items, null, 2)};
export const atmo = (id: string): Atmo | undefined => atmosphere.find((a) => a.id === id);
`;
mkdirSync(join(root, "src", "content"), { recursive: true });
writeFileSync(join(root, "src", "content", "atmosphere.generated.ts"), ts);
console.log(`atmosphere: ${items.length} image(s) → public/atmosphere, src/content/atmosphere.generated.ts`);
